#!/usr/bin/env python3
"""Self-host Nunito and generate assets/fonts/nunito.css.

Why: the page loaded Nunito from fonts.googleapis.com at runtime. That made
rendering depend on an external CDN and on swap timing — the most likely cause
of the font looking different from the original on a cold deploy. Serving the
same woff2 files from our own origin makes rendering deterministic and removes
a third-party request from the critical path.

The subset order and unicode-range values are copied verbatim from Google's
response so glyph coverage is identical; only the src URLs change.
"""
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / 'apps' / 'web' / 'public' / 'assets' / 'fonts'
CSS_OUT = FONT_DIR / 'nunito.css'
USER_AGENT = (
    'Mozilla/5.0 (X11; Linux aarch64) AppleWebKit/537.36 '
    '(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'
)
SOURCE = 'https://fonts.googleapis.com/css2?family=Nunito:wght@400;700;900&display=swap'


def fetch(url: str) -> str:
    return subprocess.run(
        ['curl', '-sS', '-H', f'User-Agent: {USER_AGENT}', url],
        capture_output=True, text=True, check=True,
    ).stdout


def main() -> int:
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    css = fetch(SOURCE)

    urls = sorted(set(re.findall(r'https://fonts\.gstatic\.com/[^)]+', css)))
    print(f'{len(urls)} font files')
    for url in urls:
        name = url.rsplit('/', 1)[-1]
        dest = FONT_DIR / name
        if not dest.exists():
            dest.write_bytes(
                subprocess.run(['curl', '-sS', url], capture_output=True, check=True).stdout
            )
        print(f'  {name}  {dest.stat().st_size:,} bytes')

    # point src at the local directory and drop the Google-specific comments
    # URL shape: https://fonts.gstatic.com/s/nunito/v32/<file>.woff2
    # Keep only the filename; the v32 path segment must be dropped too.
    local = re.sub(
        r'url\(https://fonts\.gstatic\.com/[^)]*/([^/)]+\.woff2)\)',
        r"url('/assets/fonts/\1')",
        css,
    )
    local = re.sub(r'/\* [a-z-]+ \*/\n', '', local)
    header = (
        '/* Nunito 400/700/900, self-hosted.\n'
        ' * Generated by scripts/self-host-font.py from Google Fonts CSS.\n'
        ' * Subsets and unicode-range are unchanged; only src URLs are local.\n'
        ' * Do not edit by hand. */\n'
    )
    CSS_OUT.write_text(header + local, encoding='utf-8')
    print(f'wrote {CSS_OUT.relative_to(ROOT)} ({CSS_OUT.stat().st_size:,} bytes)')
    missing = [u for u in re.findall(r"url\('([^']+)'\)", local)
               if not (ROOT / 'apps' / 'web' / 'public' / u.lstrip('/')).exists()]
    print('broken src entries:', missing or 'none')
    return 0 if not missing else 1


if __name__ == '__main__':
    raise SystemExit(main())
